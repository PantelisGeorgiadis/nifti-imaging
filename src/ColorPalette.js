import { StandardColorPalette } from './Constants.js';
import log from './log.js';

class ColorPalette {
  /**
   * Creates an instance of ColorPalette.
   * @constructor
   * @param {string} colorPalette - Color palette name from StandardColorPalette.
   */
  constructor(colorPalette) {
    this.colorPalette = colorPalette || StandardColorPalette.Grayscale;
    this._lut = ColorPalette._buildLut(this.colorPalette);
  }

  /**
   * Gets the color palette name.
   * @method
   * @returns {string} Color palette name.
   */
  getColorPalette() {
    return this.colorPalette;
  }

  /**
   * Gets the RGBA lookup table (256 entries x 4 channels).
   * @method
   * @returns {Uint8Array} RGBA lookup table.
   */
  getLut() {
    return this._lut;
  }

  /**
   * Converts a normalized value [0,1] to an RGBA color.
   * @method
   * @param {number} t - Normalized value between 0 and 1.
   * @returns {Object} RGBA color object (0-255 each).
   */
  getColor(t) {
    const idx = Math.min(255, Math.max(0, Math.round(t * 255)));
    const offset = idx * 4;
    return {
      r: this._lut[offset],
      g: this._lut[offset + 1],
      b: this._lut[offset + 2],
      a: this._lut[offset + 3],
    };
  }

  /**
   * Gets the color palette description.
   * @method
   * @returns {string} Description.
   */
  toString() {
    return `ColorPalette [${this.colorPalette}]`;
  }

  /**
   * Builds a 256-entry RGBA LUT for the given palette name.
   * @method
   * @static
   * @private
   * @param {string} paletteName - Palette name.
   * @returns {Uint8Array} RGBA lookup table.
   */
  static _buildLut(paletteName) {
    const lut = new Uint8Array(256 * 4);
    const palette = ColorPalette._palettes[paletteName];
    if (!palette) {
      log.warn(`Unknown color palette '${paletteName}', falling back to Grayscale`);
    }
    const activePalette = palette || ColorPalette._palettes[StandardColorPalette.Grayscale];
    for (let i = 0; i < 256; i++) {
      const offset = i * 4;
      lut[offset] = activePalette.r[i];
      lut[offset + 1] = activePalette.g[i];
      lut[offset + 2] = activePalette.b[i];
      lut[offset + 3] = 0xff;
    }
    return lut;
  }
}

